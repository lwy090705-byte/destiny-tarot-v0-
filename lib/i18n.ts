function buildLangPack(language: Language, pack: Record<string, string>): Record<string, string> {
  return {
    ...koTranslations,
    ...pack,
    ...getCopyrightBodies(language),
    ...getPagesMisc(language),
    ...getModalOverlay(language),
  }
}

